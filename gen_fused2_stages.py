#!/usr/bin/env python3
"""Generate fused2_stages.h, the ten gather stages of fused_LB_kernel_2 and fused_LB_kernel_bb_2.

The post-collision populations of the second-order model are

    f_l = p_l [A0 + c_l.A1/cs^2 + sum_ab c_la c_lb A2_ab/(2 cs^4)],

where A0 already contains the trace term of the second-order coefficient. The kernels store
all ten coefficients of the tile and its halo in shared memory, and every interior node pulls
each coefficient from all lattice directions. This script writes the gather of each stage explicitly, with the lattice
components and weights as literals, so that the compiler spends no operation on zero
components. The D3Q15, D3Q19 and D3Q27 lattice vectors, their order and the weight names are read
from vars_module.f90.

Usage: python3 gen_fused2_stages.py   (run from the repository root)
"""
import re

CSSQ_NAME = "invcssq"

def lattice(q):
    src = open("vars_module.f90").read()
    key = {27: "#if LATTICE == 27", 19: "#elif LATTICE == 19", 15: "#elif LATTICE == 15"}[q]
    block = src.split(key)[1]
    def arr(name):
        m = re.search(name + r"\s*=\s*\(/([^/]*)/\)", block)
        return [int(x) for x in m.group(1).replace("&", "").split(",")]
    ex, ey, ez = arr("ex"), arr("ey"), arr("ez")
    pw = re.search(r"\bp\s*=\s*\(/([^/]*)/\)", block).group(1).replace("&", "").split(",")
    pw = [x.strip() for x in pw]
    c = list(zip(ex, ey, ez))
    assert len(c) == q and c[0] == (0, 0, 0)
    for l in range(1, q, 2):
        assert c[l + 1] == tuple(-x for x in c[l]), "directions l and l+1 must be opposite"
    return c, pw

# stage: (variable, description, kind, axis indices)
STAGES = [
    ("press", "zeroth-order coefficient", "0", ()),
    ("u", "first-order coefficient along x", "1", (0,)),
    ("v", "first-order coefficient along y", "1", (1,)),
    ("w", "first-order coefficient along z", "1", (2,)),
    ("pxx", "second-order coefficient xx", "2", (0, 0)),
    ("pyy", "second-order coefficient yy", "2", (1, 1)),
    ("pzz", "second-order coefficient zz", "2", (2, 2)),
    ("pxy", "second-order coefficient xy", "2", (0, 1)),
    ("pxz", "second-order coefficient xz", "2", (0, 2)),
    ("pyz", "second-order coefficient yz", "2", (1, 2)),
]
EVEN = [("o0", ()), ("qxx", (0, 0)), ("qyy", (1, 1)), ("qzz", (2, 2)),
        ("oxy", (0, 1)), ("oxz", (0, 2)), ("oyz", (1, 2))]
ODD = [("ox", (0,)), ("oy", (1,)), ("oz", (2,))]

def prod(c, idx):
    r = 1
    for a in idx:
        r *= c[a]
    return r

def off(i, s):
    return f"l{i}" if s == 0 else (f"l{i}+{s}" if s > 0 else f"l{i}{s}")

def stages(q):
    c, pw = lattice(q)
    I = " " * 18
    out = []
    for n, (var, desc, kind, ax) in enumerate(STAGES):
        out.append(f"{I}! stage {n+1} of 10: {desc}")
        ib = n + 1
        J = I
        src = f"abuf(li,lj,lk,{ib})"
        if n == 0:
            out.append(f"{J}o0={pw[0]}*{src}")
        for l in range(1, q, 2):
            cl = c[l]
            b = prod(cl, ax)          # sign of the basis function, 0 if the direction does not contribute
            if b == 0:
                continue
            if kind == "0":
                mag = pw[l]
            elif kind == "1":
                mag = f"{pw[l]}*{CSSQ_NAME}"
            elif ax[0] == ax[1]:
                mag = f"{pw[l]}*HALF*{CSSQ_NAME}*{CSSQ_NAME}"
            else:
                mag = f"{pw[l]}*{CSSQ_NAME}*{CSSQ_NAME}"
            odd = kind == "1"
            sa, sb = ("-" if odd else "+"), ("+" if odd else "-")
            out.append(f"{J}! directions l={l} ({cl[0]},{cl[1]},{cl[2]}) and l={l+1}")
            out.append(f"{J}fa=abuf({off('i',-cl[0])},{off('j',-cl[1])},{off('k',-cl[2])},{ib})")
            out.append(f"{J}fb=abuf({off('i',cl[0])},{off('j',cl[1])},{off('k',cl[2])},{ib})")
            own = ("-" if odd else "") + src
            out += ["#ifdef BOUNCE_BACK",
                    f"{J}if(btest(isolid,{l}))fa={own}",
                    f"{J}if(btest(isolid,{l+1}))fb={own}",
                    "#endif"]
            out.append(f"{J}ge=({mag})*(fa{sa}fb)")
            out.append(f"{J}go=({mag})*(fa{sb}fb)")
            for name, idx in EVEN:
                t = prod(cl, idx)
                if t:
                    out.append(f"{J}{name}={name}{'+' if t*b > 0 else '-'}ge")
            for name, idx in ODD:
                t = prod(cl, idx)
                if t:
                    out.append(f"{J}{name}={name}{'+' if t*b > 0 else '-'}go")
        out.append("")
    return out

HEADER = [
    "!     fused2_stages.h: generated by gen_fused2_stages.py, do not edit by hand.",
    "!     Ten gather stages of fused_LB_kernel_2 and fused_LB_kernel_bb_2. All ten post-collision",
    "!     Hermite coefficients of the tile and its halo are already in shared memory; stage k adds",
    "!     the contribution of coefficient k from every direction pair (l, l+1) to the output",
    "!     moments: ge to those even in the lattice velocity, go to the odd ones. With BOUNCE_BACK,",
    "!     a coefficient pulled from a solid node is replaced by the value of this node, with the",
    "!     sign of the reflected direction.",
]

def main():
    lines = HEADER + ["#if LATTICE == 19"]
    lines += stages(19)
    lines.append("#elif LATTICE == 27")
    lines += stages(27)
    lines.append("#elif LATTICE == 15")
    lines += stages(15)
    lines.append("#endif")
    open("fused2_stages.h", "w").write("\n".join(lines) + "\n")

if __name__ == "__main__":
    main()
