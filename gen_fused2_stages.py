#!/usr/bin/env python3
"""Generate the gather stages of the fused collide-and-stream kernels.

fused2_stages.h holds the ten stages of the second-order coefficients, used by fused_LB_kernel and
fused_LB_kernel_bb and, for D3Q27, also by the high-order kernels fused_LB_kernel_h and
fused_LB_kernel_bb_h. fusedh_stages.h holds the seventeen stages of the high-order coefficients
(orders three to six) of D3Q27, used by the high-order kernels.

The post-collision populations of the second-order model are

    f_l = p_l [A0 + c_l.A1/cs^2 + sum_ab c_la c_lb A2_ab/(2 cs^4)],

where A0 already contains the trace term of the second-order coefficient. The kernels store
all ten coefficients of the tile and its halo in shared memory, and every interior node pulls
each coefficient from all lattice directions. This script writes the gather of each stage explicitly, with the lattice
components and weights as literals, so that the compiler spends no operation on zero
components. The D3Q15, D3Q19 and D3Q27 lattice vectors, their order and the weight names are read
from vars_module.f90.

Usage: python3 gen_fused2_stages.py   (run from the repository root)
"""
import re
from fractions import Fraction

CSSQ_NAME = "invcssq"

def lattice(q):
    src = open("vars_module.f90").read()
    key = {27: "#if LATTICE == 27", 19: "#elif LATTICE == 19", 15: "#elif LATTICE == 15"}[q]
    block = src.split(key)[1]
    def arr(name):
        m = re.search(name + r"\s*=\s*\(/([^/]*)/\)", block)
        return [int(x) for x in m.group(1).replace("&", "").split(",")]
    ex, ey, ez = arr("ex"), arr("ey"), arr("ez")
    pw = re.search(r"\bp\s*=\s*\(/([^/]*)/\)", block).group(1).replace("&", "").split(",")
    pw = [x.strip() for x in pw]
    c = list(zip(ex, ey, ez))
    assert len(c) == q and c[0] == (0, 0, 0)
    for l in range(1, q, 2):
        assert c[l + 1] == tuple(-x for x in c[l]), "directions l and l+1 must be opposite"
    return c, pw

# stage: (variable, description, kind, axis indices)
STAGES = [
    ("press", "zeroth-order coefficient", "0", ()),
    ("u", "first-order coefficient along x", "1", (0,)),
    ("v", "first-order coefficient along y", "1", (1,)),
    ("w", "first-order coefficient along z", "1", (2,)),
    ("pxx", "second-order coefficient xx", "2", (0, 0)),
    ("pyy", "second-order coefficient yy", "2", (1, 1)),
    ("pzz", "second-order coefficient zz", "2", (2, 2)),
    ("pxy", "second-order coefficient xy", "2", (0, 1)),
    ("pxz", "second-order coefficient xz", "2", (0, 2)),
    ("pyz", "second-order coefficient yz", "2", (1, 2)),
]
EVEN = [("o0", ()), ("qxx", (0, 0)), ("qyy", (1, 1)), ("qzz", (2, 2)),
        ("oxy", (0, 1)), ("oxz", (0, 2)), ("oyz", (1, 2))]
ODD = [("ox", (0,)), ("oy", (1,)), ("oz", (2,))]

def prod(c, idx):
    r = 1
    for a in idx:
        r *= c[a]
    return r

def off(i, s):
    return f"l{i}" if s == 0 else (f"l{i}+{s}" if s > 0 else f"l{i}{s}")

def stages(q):
    c, pw = lattice(q)
    I = " " * 18
    out = []
    for n, (var, desc, kind, ax) in enumerate(STAGES):
        out.append(f"{I}! stage {n+1} of 10: {desc}")
        ib = n + 1
        J = I
        src = f"abuf(li,lj,lk,{ib})"
        if n == 0:
            out.append(f"{J}o0={pw[0]}*{src}")
        for l in range(1, q, 2):
            cl = c[l]
            b = prod(cl, ax)          # sign of the basis function, 0 if the direction does not contribute
            if b == 0:
                continue
            if kind == "0":
                mag = pw[l]
            elif kind == "1":
                mag = f"{pw[l]}*{CSSQ_NAME}"
            elif ax[0] == ax[1]:
                mag = f"{pw[l]}*HALF*{CSSQ_NAME}*{CSSQ_NAME}"
            else:
                mag = f"{pw[l]}*{CSSQ_NAME}*{CSSQ_NAME}"
            odd = kind == "1"
            sa, sb = ("-" if odd else "+"), ("+" if odd else "-")
            out.append(f"{J}! directions l={l} ({cl[0]},{cl[1]},{cl[2]}) and l={l+1}")
            out.append(f"{J}fa=abuf({off('i',-cl[0])},{off('j',-cl[1])},{off('k',-cl[2])},{ib})")
            out.append(f"{J}fb=abuf({off('i',cl[0])},{off('j',cl[1])},{off('k',cl[2])},{ib})")
            own = ("-" if odd else "") + src
            out += ["#ifdef BOUNCE_BACK",
                    f"{J}if(btest(isolid,{l}))fa={own}",
                    f"{J}if(btest(isolid,{l+1}))fb={own}",
                    "#endif"]
            out.append(f"{J}ge=({mag})*(fa{sa}fb)")
            out.append(f"{J}go=({mag})*(fa{sb}fb)")
            for name, idx in EVEN:
                t = prod(cl, idx)
                if t:
                    out.append(f"{J}{name}={name}{'+' if t*b > 0 else '-'}ge")
            for name, idx in ODD:
                t = prod(cl, idx)
                if t:
                    out.append(f"{J}{name}={name}{'+' if t*b > 0 else '-'}go")
        out.append("")
    return out

HEADER = [
    "!     fused2_stages.h: generated by gen_fused2_stages.py, do not edit by hand.",
    "!     Ten gather stages of the second-order fused_LB_kernel and fused_LB_kernel_bb. All ten post-collision",
    "!     Hermite coefficients of the tile and its halo are already in shared memory; stage k adds",
    "!     the contribution of coefficient k from every direction pair (l, l+1) to the output",
    "!     moments: ge to those even in the lattice velocity, go to the odd ones. With BOUNCE_BACK,",
    "!     a coefficient pulled from a solid node is replaced by the value of this node, with the",
    "!     sign of the reflected direction.",
]

def main():
    lines = HEADER + ["#if LATTICE == 19"]
    lines += stages(19)
    lines.append("#elif LATTICE == 27")
    lines += stages(27)
    lines.append("#elif LATTICE == 15")
    lines += stages(15)
    lines.append("#endif")
    open("fused2_stages.h", "w").write("\n".join(lines) + "\n")

# high-order D3Q27 basis: index k of Minv_mrt, name, exponents of (c_x, c_y, c_z)
HIGH = [(10, "xxy", (2, 1, 0)), (11, "xxz", (2, 0, 1)), (12, "xyy", (1, 2, 0)), (13, "xzz", (1, 0, 2)),
        (14, "yzz", (0, 1, 2)), (15, "yyz", (0, 2, 1)), (16, "xyz", (1, 1, 1)), (17, "xxyy", (2, 2, 0)),
        (18, "xxzz", (2, 0, 2)), (19, "yyzz", (0, 2, 2)), (20, "xyzz", (1, 1, 2)), (21, "xyyz", (1, 2, 1)),
        (22, "xxyz", (2, 1, 1)), (23, "xxyzz", (2, 1, 2)), (24, "xxyyz", (2, 2, 1)), (25, "xyyzz", (1, 2, 2)),
        (26, "xxyyzz", (2, 2, 2))]
CS2 = Fraction(1, 3)

def exact_weights():
    """Exact D3Q27 weights p0..p3 from their definitions in vars_module.f90."""
    block = open("vars_module.f90").read().split("#if LATTICE == 27")[1]
    w = {}
    for name in ("p0", "p1", "p2", "p3"):
        m = re.search(name + r"\s*=\s*real\(\s*([0-9.]+)d0\s*/\s*([0-9.]+)d0", block)
        w[name] = Fraction(int(float(m.group(1))), int(float(m.group(2))))
    return w

def minv(expo, c, wl):
    """Element of Minv_mrt: p_l H_k(c_l) / N_k for the tensor-product Hermite basis."""
    val = wl
    for e, ci in zip(expo, c):
        if e == 1:
            val *= Fraction(ci) / CS2
        elif e == 2:
            val *= (Fraction(ci * ci) - CS2) / (2 * CS2 * CS2)
    return val

def lit(f):
    return f"real({f.numerator}.d0/{f.denominator}.d0,kind=db)"

def stages_high():
    c, pw = lattice(27)
    wx = exact_weights()
    I = " " * 18
    names = [nm for nm, _ in EVEN] + [nm for nm, _ in ODD]
    # the many small high-order contributions are summed in separate accumulators, which are
    # added to the output moments once at the end: this limits the round-off in single precision
    out = [f"{I}h{nm}=ZERO" for nm in names] + [""]
    for n, (k, name, expo) in enumerate(HIGH):
        s = n + 1
        src = f"abuf(li,lj,lk,{s})"
        odd = sum(1 for e in expo if e == 1) % 2 == 1
        out.append(f"{I}! high-order stage {s} of 17: coefficient {name} (k={k} in Minv_mrt)")
        # by orthogonality, sum_l T_j(c_l) Minv(k,l) vanishes for every output moment j, so the value of
        # this node can be subtracted from the pulled values: this removes the rest direction and
        # avoids the cancellation of large terms in single precision
        out.append(f"{I}fc={src}")
        for l in range(1, 27, 2):
            cl = c[l]
            C = minv(expo, cl, wx[pw[l]])
            if C == 0:
                continue
            sa, sb = ("-" if odd else "+"), ("+" if odd else "-")
            out.append(f"{I}! directions l={l} ({cl[0]},{cl[1]},{cl[2]}) and l={l+1}")
            out.append(f"{I}fa=abuf({off('i',-cl[0])},{off('j',-cl[1])},{off('k',-cl[2])},{s})")
            out.append(f"{I}fb=abuf({off('i',cl[0])},{off('j',cl[1])},{off('k',cl[2])},{s})")
            own = ("-" if odd else "") + "fc"
            out += ["#ifdef BOUNCE_BACK",
                    f"{I}if(btest(isolid,{l}))fa={own}",
                    f"{I}if(btest(isolid,{l+1}))fb={own}",
                    "#endif"]
            if odd:
                out.append(f"{I}ge={lit(C)}*(fa-fb)")
                out.append(f"{I}go={lit(C)}*(fa+fb-TWO*fc)")
            else:
                out.append(f"{I}ge={lit(C)}*(fa+fb-TWO*fc)")
                out.append(f"{I}go={lit(C)}*(fa-fb)")
            for nm, idx in EVEN:
                t = prod(cl, idx)
                if t:
                    out.append(f"{I}h{nm}=h{nm}{'+' if t > 0 else '-'}ge")
            for nm, idx in ODD:
                t = prod(cl, idx)
                if t:
                    out.append(f"{I}h{nm}=h{nm}{'+' if t > 0 else '-'}go")
        out.append("")
    return out

HEADER_H = [
    "!     fusedh_stages.h: generated by gen_fused2_stages.py, do not edit by hand.",
    "!     Seventeen gather stages of fused_LB_kernel_h and fused_LB_kernel_bb_h. The post-collision",
    "!     Hermite coefficients of orders three to six of the tile and its halo are in shared memory;",
    "!     stage s adds the contribution of coefficient s from every direction pair (l, l+1) to the",
    "!     output moments, with the elements of Minv_mrt as exact fractions. The value of this node",
    "!     is subtracted from the pulled values, which leaves the exact result unchanged by orthogonality",
    "!     and reduces round-off. The contributions are summed in separate accumulators (prefix h) and",
    "!     added to the output moments at the end. With BOUNCE_BACK, a coefficient pulled from a solid node",
    "!     is replaced by the value of this node, with the sign of the reflected direction.",
]

def main_high():
    I = " " * 18
    tail = [f"{I}{nm}={nm}+h{nm}" for nm, _ in EVEN + ODD]
    lines = HEADER_H + ["#if LATTICE == 27"] + stages_high() + tail + ["#endif"]
    open("fusedh_stages.h", "w").write("\n".join(lines) + "\n")

if __name__ == "__main__":
    main()
    main_high()
